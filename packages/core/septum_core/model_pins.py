from dataclasses import dataclass
from types import MappingProxyType
from typing import Literal, Mapping

ModelKind = Literal["hf-transformers", "sentence-transformers", "paddle"]


@dataclass(frozen=True)
class ModelPin:
    """One model repository pinned to a commit with per-file SHA256 hashes."""

    repo_id: str
    revision: str
    kind: ModelKind
    files: Mapping[str, str]


def _pin(
    repo_id: str, revision: str, kind: ModelKind, files: dict[str, str]
) -> ModelPin:
    """Build a pin whose file table is read-only."""
    return ModelPin(repo_id, revision, kind, MappingProxyType(files))


