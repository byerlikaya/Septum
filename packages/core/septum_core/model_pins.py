"""Pinned revisions and file hashes of every default model Septum loads.

Data only. Generated by the developer tool ``pin_models.py --write-manifest``
from each repository's ``main`` commit; do not edit by hand. Keys are Hub
repo ids. ``revision`` is the 40-hex commit the files are fetched at and
``files`` maps every file the loader reads (repo-relative path) to its
SHA256. Weights are safetensors for the transformer kinds and Paddle
inference files for the OCR kind; no pickle weight is pinned.
"""

